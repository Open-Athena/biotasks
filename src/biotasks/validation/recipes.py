"""Recognize the supported upstream recipe without rewriting grading assets."""

import re

from biotasks.validation.files import require


def native_prefix(raw: bytes) -> tuple[bytes, str]:
    marker = b"# Per-task overlay (from pipeline-emitted Dockerfile)"
    require(
        raw.startswith(b"# Auto-generated by Repo2RLEnv (inline mode)") and raw.count(marker) == 1,
        "unsupported_initializer: expected native inline Dockerfile",
    )
    prefix = raw.split(marker)[0]
    refs = re.findall(rb"^FROM\s+(\S+)", prefix, re.M)
    require(
        len(refs) == 1 and not refs[0].startswith((b"local/", b"sha256:")),
        "unsupported_initializer: public FROM required",
    )
    ref = refs[0].decode()
    require(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9./_:@-]*", ref), "Invalid public image reference")
    return prefix, ref


def tagged_recipe(raw: bytes, owner: str) -> bytes:
    lines = raw.splitlines(keepends=True)
    positions = [i for i, line in enumerate(lines) if line.upper().startswith(b"FROM ")]
    require(len(positions) == 1, "Only single-stage native recipes are supported")
    lines.insert(positions[0] + 1, ("LABEL biotasks.run=" + owner + "\n").encode())
    return b"".join(lines)
