def test_intent_is_durable_before_effect_and_recovery_is_distinct(tmp_path: Path) -> None:
    input_file = tmp_path / "input"
    input_file.write_text("original")
    evidence = tmp_path / "evidence.json"
    journal = tmp_path / "journal.json"

    class Adapter:
        def probe(self, stage: str) -> Observation:
            return (
                Observation("ready", (Binding(str(evidence), sha(evidence)),))
                if evidence.exists()
                else Observation("absent")
            )

        def verify(self, stage: str, bindings: tuple[Binding, ...]) -> None:
            assert read_json(Path(bindings[0].path)) == {"valid": True}

        def perform(self, stage: str) -> None:
            assert read_json(journal)["intent"]["stage"] == "one"
            raise RuntimeError("before effect")

        def recover(self, stage: str) -> None:
            write_json(evidence, {"valid": True})

    adapter = Adapter()
    inputs = (Binding(str(input_file), sha(input_file)),)
    with pytest.raises(RuntimeError, match="before effect"):
        advance("fixed", inputs, journal, adapter, ("one",))
    assert advance("fixed", inputs, journal, adapter, ("one",)) == "recovering:one"
    assert advance("fixed", inputs, journal, adapter, ("one",)) == "one"
    assert advance("fixed", inputs, journal, adapter, ("one",)) == "complete"
    input_file.write_text("changed")
    with pytest.raises(ValidationError, match="Evidence changed"):
        advance("fixed", inputs, journal, adapter, ("one",))


