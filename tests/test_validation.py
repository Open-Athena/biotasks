def compressed(files: dict[str, bytes]) -> bytes:
    stream = io.BytesIO()
    with tarfile.open(fileobj=stream, mode="w") as archive:
        for name, data in files.items():
            member = tarfile.TarInfo(name)
            member.size = len(data)
            archive.addfile(member, io.BytesIO(data))
    return zstandard.ZstdCompressor().compress(stream.getvalue())


class Remote:
    """Native *failure* fixture; no biological or Harbor execution is simulated as success."""

    def __init__(self, root: Path, monkeypatch: pytest.MonkeyPatch):
        self.root = root
        self.jobs: dict[str, dict[str, Any]] = {}
        self.submissions: list[str] = []
        self.fail_after_rpc = False
        self.empty = False
        self.zero_attempts = False
        self.pending = False
        monkeypatch.setattr(bridge, "call", self.call)
        monkeypatch.setattr(collection, "download", self.download)

    def call(self, backend: dict[str, Any], request: dict[str, Any], log: Path) -> dict[str, Any]:
        if request["action"] == "fingerprint":
            return {"synthetic": True}
        group = request["group"]
        run = group["run_id"]
        if request["action"] == "preflight":
            assert run not in self.jobs
            return {"run_id": run, "worker_id": "fixture-worker"}
        if request["action"] == "submit":
            assert run not in self.jobs, "Duplicate fixed-handle submission"
            receipt = {
                "job_id": "/exedev/" + run,
                "worker_id": "fixture-worker",
                "worker_tpu_name": "fixture-tpu",
                "payload_sha256": group["payload_sha256"],
                "state": "submission_pending",
            }
            write_json(Path(request["submission_file"]), receipt)
            self.jobs[run] = self.output(group, request)
            self.submissions.append(run)
            if self.fail_after_rpc:
                self.fail_after_rpc = False
                raise RuntimeError("Interrupted after RPC before parent receipt")
            return receipt
        assert request["action"] == "observe"
        if run not in self.jobs:
            return {"state": "handle_missing"}
        if self.pending:
            return {"state": "running"}
        return self.jobs[run]

    def output(self, group: dict[str, Any], request: dict[str, Any]) -> dict[str, Any]:
        run = group["run_id"]
        config = read_json(Path(request["payload_directory"]) / "family.json")
        role = config["operation"]
        if role == "execute" and self.zero_attempts:
            return {
                "job_id": "/exedev/" + run,
                "terminal": True,
                "state": "failed",
                "attempts": 0,
                "allocated_cpu_hours": 0,
                "output_archive": {"state": "empty"},
                "verified_no_creation": True,
            }
        data: dict[str, bytes] = {}
        report = {
            "run_id": config["run_id"],
            "worker_id": "fixture-worker",
            "operation": role,
            "configuration_verified": True,
            "finished": 1,
            "creation_started": True,
            "controls_started": False,
            "stage": "bootstrap_build_failed",
            "payload_sha256": {
                n: v for n, v in group["payload_sha256"].items() if n != "payload.json"
            },
        }
        if role == "execute":
            data["input-package.tar.gz"] = (
                Path(request["payload_directory"]) / "tasks.tar.gz"
            ).read_bytes()
            data["control-artifacts.tar.gz"] = data["input-package.tar.gz"]
            report["stop"] = {"verified_stopped": True}
        elif role == "stop":
            report["stop"] = {"verified_stopped": True}
        else:
            report["cleanup"] = {
                "verified_empty": True,
                "remaining": {"containers": [], "controllers": [], "images": [], "volumes": []},
            }
        report["output_sha256"] = {n: content_sha(raw) for n, raw in data.items()}
        data["result.json"] = json.dumps(report).encode()
        raw = compressed(data)
        file = self.root / (run + ".tar.zst")
        file.write_bytes(raw)
        return {
            "job_id": "/exedev/" + run,
            "terminal": True,
            "state": "succeeded",
            "attempts": 1,
            "allocated_cpu_hours": 0.01,
            "output_archive": {
                "state": "empty" if self.empty and role == "execute" else "uploaded",
                "fixture_path": str(file),
            },
        }

    def download(self, account: dict[str, Any], directory: Path, gcloud: str) -> Path:
        assert account["terminal"]
        if account["output_archive"]["state"] == "empty":
            raise ValidationError("No uploaded execution archive")
        target = directory / "runtime.tar.zst"
        target.write_bytes(Path(account["output_archive"]["fixture_path"]).read_bytes())
        return target


def finish(root: Path, maximum: int = 50) -> dict[str, Any]:
    for _ in range(maximum):
        state = controller.run(root, once=True)
        if state["state"] != "in_progress":
            return state
    pytest.fail("Journal failed to converge")


@pytest.mark.parametrize("boundary", STAGES)
def test_resume_after_every_durable_stage_effect(
    prepared: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch, boundary: str
) -> None:
    root, _ = prepared
    remote = Remote(root, monkeypatch)
    original = controller.Pipeline.record
    interrupted = False

    def record(self: controller.Pipeline, stage: str, paths: list[Path], **value: Any) -> None:
        nonlocal interrupted
        original(self, stage, paths, **value)
        if stage == boundary and not interrupted:
            interrupted = True
            raise RuntimeError("after effect, before journal commit")

    monkeypatch.setattr(controller.Pipeline, "record", record)
    with pytest.raises(RuntimeError, match="before journal"):
        finish(root)
    assert finish(root)["state"] == "complete"
    assert len(remote.submissions) == 2  # primary + cleanup, no duplicate or stop job
    group = read_json(root / "plan.json")["tasks"][0]
    readback = read_json(root / "runs" / group["id"] / "readback.json")
    assert readback["stage"] == "bootstrap_build_failed"
    assert readback["positive_control_pair"] is False
    ledger = Path(read_json(root / "plan.json")["budget_ledger"])
    before = ledger.read_bytes()
    monkeypatch.setattr(
        bridge, "call", lambda *a, **k: pytest.fail("Completed reinvoke must be inert")
    )
    assert finish(root)["state"] == "complete"
    assert ledger.read_bytes() == before


