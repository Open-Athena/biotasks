def test_worker_finish_stops_before_archiving_and_never_removes_data(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    from subprocess import CompletedProcess

    from biotasks.validation.worker.job import Supervisor

    monkeypatch.setenv("IRIS_WORKER_ID", "fixture")
    out = tmp_path / "output"
    out.mkdir()
    runner = Supervisor(tmp_path, out, {"run_id": "fixed", "operation": "execute"})
    runner.tools.mkdir()
    (runner.tools / "docker").touch()
    runner.report.update(creation_started=True, controller_created=True)
    calls: list[tuple[str, ...]] = []

    def docker(*args: str, **kwargs: Any) -> CompletedProcess[str]:
        calls.append(args)
        return CompletedProcess(args, 0, "", "")

    def stop() -> dict[str, Any]:
        calls.append(("stop_execution",))
        return {"verified_stopped": True}

    monkeypatch.setattr(runner, "docker", docker)
    monkeypatch.setattr(runner, "stop_execution", stop)
    runner.finish()
    assert calls[0] == calls[-1] == ("stop_execution",)
    assert any(args[0] == "cp" for args in calls)
    assert not any(args[0] in ("rm", "rmi", "volume") for args in calls)
    assert read_json(out / "result.json")["retained_resources"]["volume"] == "fixed-work"


@pytest.mark.parametrize("changed_existing", [False, True])
def test_partial_publication_recovers_missing_objects_without_overwriting(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, changed_existing: bool
) -> None:
    from types import SimpleNamespace

    import huggingface_hub

    source = tmp_path / "input.json"
    source.write_text("synthetic fixture\n")
    preservation.prepare(tmp_path, {"input.json": source}, {"synthetic": True})
    objects: dict[str, bytes] = {}
    writes: list[str] = []
    interrupted = False

    class API:
        def bucket_info(self, bucket: str) -> Any:
            return SimpleNamespace(private=False)

        def list_bucket_tree(self, bucket: str, **kwargs: Any) -> Any:
            return [SimpleNamespace(type="file", path=n) for n in objects]

        def batch_bucket_files(self, bucket: str, *, add: list[tuple[str, str]]) -> None:
            nonlocal interrupted
            for path, name in add:
                assert name not in objects, "Never overwrite a partial snapshot"
                objects[name] = Path(path).read_bytes()
                writes.append(name)
                if not interrupted:
                    interrupted = True
                    raise RuntimeError("Upload succeeded before acknowledgement")

        def download_bucket_files(
            self, bucket: str, files: list[tuple[str, Path]], **kwargs: Any
        ) -> None:
            assert kwargs["token"] is False
            for name, path in files:
                Path(path).write_bytes(objects[name])

    monkeypatch.setattr(huggingface_hub, "HfApi", API)
    archive = {"kind": "hf-public", "bucket": "synthetic/fixture", "prefix": "research/fixture"}
    policy = {"eligible": True, "review": "synthetic inputs only"}
    with pytest.raises(RuntimeError, match="before acknowledgement"):
        preservation.publish(tmp_path, archive, policy)
    if changed_existing:
        objects[next(iter(objects))] = b"changed"
        with pytest.raises(ValidationError, match="Anonymous readback differs"):
            preservation.publish(tmp_path, archive, policy)
        assert len(writes) == 1
        assert not (tmp_path / "publication.json").exists()
    else:
        preservation.publish(tmp_path, archive, policy)
        preservation.verify_receipt(tmp_path)
        assert len(writes) == len(set(writes)) == 2
    assert not list(tmp_path.glob(".anonymous-readback-*"))
    assert not (tmp_path / "hf-transfer-cache").exists()


