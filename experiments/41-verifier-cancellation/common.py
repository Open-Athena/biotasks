UPSTREAM='27d04ee8203cd5b2f20c3997d13836e5f5b64238'
MAX_FILE=1024**2
MAX_ARCHIVE=8*1024**2


def sha(path):
    with Path(path).open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()


def content_sha(raw):return hashlib.sha256(raw).hexdigest()


def json_sha(data):return content_sha(json.dumps(data,sort_keys=True,separators=(',',':')).encode())


def write(path,value):
    from resume_runner import atomic_write
    atomic_write(path,value)


def safe(name):
    path=PurePosixPath(name)
    if path.is_absolute() or '..' in path.parts or not path.parts:raise ValueError('Unsafe artifact path')
    return path


def inventory(root):
    root=Path(root);rows=[]
    for path in sorted(root.rglob('*')):
        assert not path.is_symlink()
        if path.is_file():
            assert path.stat().st_size<MAX_FILE
            rows.append(dict(path=str(path.relative_to(root)),bytes=path.stat().st_size,
                mode=oct(path.stat().st_mode&0o777)[2:],sha256=sha(path)))
    return rows


def task_identity(repo,task,rows):
    return json_sha(dict(schema='biotasks-task-files-v1',repo=repo,task=task,
        files=[dict(path=r['path'],bytes=r['bytes'],mode=int(r['mode'],8),sha256=r['sha256']) for r in sorted(rows,key=lambda r:r['path'])]))


def native_prefix(raw):
    marker=b'# Per-task overlay (from pipeline-emitted Dockerfile)'
    assert raw.count(marker)==1 and raw.startswith(b'# Auto-generated by Repo2RLEnv (inline mode)')
    prefix=raw.split(marker)[0]
    refs=re.findall(rb'^FROM\s+(\S+)',prefix,re.M)
    assert len(refs)==1 and not refs[0].startswith((b'local/',b'sha256:'))
    assert re.fullmatch(rb'[A-Za-z0-9./_:@-]+',refs[0])
    return prefix,refs[0].decode()


def archive_tree(root,destination):
    root=Path(root);destination=Path(destination);assert not destination.exists()
    rows=inventory(root)
    with destination.open('wb') as stream,gzip.GzipFile(fileobj=stream,mode='wb',filename='',mtime=0) as gz,tarfile.open(fileobj=gz,mode='w|') as tar:
        for row in rows:
            path=root/row['path'];member=tarfile.TarInfo(row['path'])
            member.size=row['bytes'];member.mode=int(row['mode'],8)
            with path.open('rb') as data:tar.addfile(member,data)
    assert destination.stat().st_size<MAX_ARCHIVE
    # Independent inventory readback, not just a digest of the writer's output.
    unpack_task_archive(destination,rows,None)
    return dict(path=str(destination),bytes=destination.stat().st_size,sha256=sha(destination),files=rows)


def unpack_task_archive(archive,rows,destination):
    specs={r['path']:r for r in rows};seen=set();total=0
    with tarfile.open(archive,'r:gz') as tar:
        for member in tar:
            path=safe(member.name)
            assert member.isfile() and member.name in specs and member.name not in seen
            spec=specs[member.name];seen.add(member.name);total+=member.size
            assert total<32*1024**2 and member.size==spec['bytes']<MAX_FILE
            assert member.mode==int(spec['mode'],8)
            raw=tar.extractfile(member).read();assert content_sha(raw)==spec['sha256']
            if destination is not None:
                target=Path(destination)/path;target.parent.mkdir(parents=True,exist_ok=True)
                assert not target.exists();target.write_bytes(raw);target.chmod(member.mode)
    assert seen==set(specs)


